"""Auto-generate reports/results.md from the JSON outputs of the pipeline (no hand-typed numbers)."""
from __future__ import annotations

import datetime as dt
import json

from .calibration import read_meta
from .config import CRITICAL, DISCLAIMER, REPORTS, WARNING


def _load(name):
    p = REPORTS / name
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else None


def _pct(x):
    return "n/a" if x is None else f"{100 * x:.1f}%"


def write_results() -> str:
    meta = read_meta()
    nd = _load("nextday_metrics.json")
    s2 = _load("spike2h_metrics.json")
    ls = _load("lifesnaps_validation.json")
    L = ["# SleepTwin - Results (auto-generated)", "",
         f"_Generated by code (`src/report.py`) on {dt.date.today()}. Every number below is computed by the "
         "pipeline; slides must quote these values._", "",
         f"> {DISCLAIMER} All patient data is **simulated**.", ""]

    L += ["## 1. Cohort (simulated) and sanity targets", "",
          "| Check | Value | Target (plan 6.6) |", "|---|---|---|",
          f"| Virtual patients x days | {meta.get('n_patients')} x {meta.get('n_days')} | 300 x 21 |",
          f"| EHR calibration source | {meta.get('ehr_calibration')} | NHANES 2017-Mar 2020 |",
          f"| Wearable calibration source | {meta.get('wearable_calibration')} | LifeSnaps |"]
    mix = meta.get("cohort_mix", {})
    L += [f"| T2D / prediabetes / HTN / OSA (true) / OSA diagnosed | {_pct(mix.get('t2d'))} / "
          f"{_pct(mix.get('prediabetes'))} / {_pct(mix.get('htn'))} / {_pct(mix.get('osa_true'))} / "
          f"{_pct(mix.get('osa_diagnosed'))} | ~40% / ~25% / ~45% / ~20% |",
          f"| CGM range (mg/dL) | {meta.get('glucose_min', 0):.0f} - {meta.get('glucose_max', 0):.0f} | within 60-350 |",
          f"| SI drop, 4 nights x 5 h vs 7.5 h | {_pct(meta.get('si_drop_4x5h_check'))} | ~25% |",
          f"| Next-day glucose event rate (days 15-21) | {_pct(meta.get('event_rate_glucose_pred_days'))} | 15-30% |",
          f"| Morning BP event rate (days 15-21) | {_pct(meta.get('event_rate_bp_pred_days'))} | - |",
          f"| Missing nights / CGM missing | {_pct(meta.get('missing_nights_pct'))} / "
          f"{_pct(meta.get('cgm_missing_pct'))} | ~5% |", ""]
    if meta.get("event_rate_by_group"):
        g = meta["event_rate_by_group"]
        L += ["Glucose event rate by group: " + ", ".join(f"{k} {_pct(v)}" for k, v in g.items()), ""]

    if nd:
        L += ["## 2. Next-day model - 3-tier ablation", "",
              f"{nd['n_rows']} patient-days ({nd['n_patients']} patients x prediction days {nd['prediction_days']}), "
              f"{nd['cv']}. Fixed alert threshold 0.5; 7 prediction days = 1 patient-week.", ""]
        for target, title in (("glucose_event_24h", "Main: tomorrow's CGM peak > 180 mg/dL"),
                              ("bp_event", "Secondary: morning SBP > 145 mmHg")):
            r = nd[target]
            L += [f"### {title}", "", "| Model | AUROC | AUPRC | Sensitivity | Specificity | False alerts / patient-week |",
                  "|---|---|---|---|---|---|"]
            for tier, name in (("ehr_only", "EHR-only (static + genetic)"), ("wearables_only", "Wearables-only"),
                               ("fused", "**Fused twin**")):
                m = r[tier]
                L.append(f"| {name} | {m['auroc']:.3f} | {m['auprc']:.3f} | {m['sensitivity']:.2f} | "
                         f"{m['specificity']:.2f} | {m['false_alerts_per_patient_week']:.2f} |")
            L += ["", f"Prevalence: {_pct(r['fused']['prevalence'])}. **Interpretation:** {r['interpretation']}", ""]
            if r.get("t2d_subgroup"):
                t = r["t2d_subgroup"]
                L += [f"T2D-only subgroup (harder, within-diabetic discrimination): AUROC EHR-only "
                      f"{t['ehr_only']:.3f} / wearables-only {t['wearables_only']:.3f} / fused {t['fused']:.3f}.", ""]
        if nd.get("top_features_glucose"):
            L += ["Top fused-model features (mean |SHAP|): " +
                  ", ".join(f"`{k}` {v:.2f}" for k, v in list(nd["top_features_glucose"].items())[:8]), ""]
        if nd.get("personas"):
            L += ["### Demo personas (out-of-fold forecasts for day 21)", "",
                  "| Persona | Glucose risk | BP risk | Band | Expected |", "|---|---|---|---|---|"]
            exp = {"A": "Critical (~80%+)", "B": "Warning (~65-75%)", "C": "Stable (<20%)"}
            for pid, v in nd["personas"].items():
                m = max(v["glucose_risk"], v["bp_risk"])
                band = "Critical" if m >= CRITICAL else "Warning" if m >= WARNING else "Stable"
                L.append(f"| {pid} | {_pct(v['glucose_risk'])} | {_pct(v['bp_risk'])} | {band} | {exp[pid]} |")
            L += ["", f"Bands use max(glucose, BP) risk: Critical >= {CRITICAL:.0%}, Warning >= {WARNING:.0%}.", ""]

    if s2:
        L += ["## 3. 2-hour glucose spike alert", "",
              f"{s2['n_samples']} hourly samples (07:00-21:00, CGM < 160 mg/dL) from {s2['n_patients']} patients; "
              f"event rate {_pct(s2['event_rate'])} (target 5-20%).", "",
              "| Metric | Value |", "|---|---|",
              f"| AUROC | {s2['auroc']:.3f} |", f"| AUPRC | {s2['auprc']:.3f} |",
              f"| Plain CGM-trend baseline AUROC (current value + 30-min slope) | {s2['trend_only_auroc']:.3f} |",
              f"| Alert threshold | {s2['threshold']} |", f"| Sensitivity (samples) | {s2['sensitivity']:.2f} |",
              f"| Spike episodes warned | {s2['episodes_warned']} / {s2['episodes']} ({_pct(s2['episode_recall'])}) |",
              f"| **Median warning lead time** | **{s2['median_lead_min']:.0f} min** "
              f"(IQR {s2['iqr_lead_min'][0]:.0f}-{s2['iqr_lead_min'][1]:.0f}) |",
              f"| False alerts / patient-week | {s2['false_alerts_per_patient_week']:.2f} |", "",
              f"**Interpretation:** the twin warns about {_pct(s2['episode_recall'])} of spikes a median "
              f"{s2['median_lead_min']:.0f} minutes before they happen, beating a plain trend arrow "
              f"(AUROC {s2['auroc']:.2f} vs {s2['trend_only_auroc']:.2f}) because it also knows the meal, "
              "last night's sleep and the patient's record.", ""]

    if ls:
        L += ["## 4. Real-data validation (LifeSnaps, real Fitbit volunteers)", ""]
        if ls.get("available"):
            L += [f"- {ls['n_users']} users, {ls['n_nights']} nights ({ls['n_short_nights']} short); "
                  f"{ls['definition']}.",
                  f"- Resting HR z-score: short {ls['rhr_z_short_mean']:+.2f} vs normal {ls['rhr_z_normal_mean']:+.2f} "
                  f"(paired median diff {ls['rhr_paired_diff_median']:+.2f} SD; {ls['rhr_users_higher_after_short_pct']:.0f}% "
                  f"of users higher; Wilcoxon p = {ls['rhr_wilcoxon_p']:.2g}).",
                  f"- HRV z-score: short {ls['hrv_z_short_mean']:+.2f} vs normal {ls['hrv_z_normal_mean']:+.2f} "
                  f"(paired median diff {ls['hrv_paired_diff_median']:+.2f} SD; {ls['hrv_users_lower_after_short_pct']:.0f}% "
                  f"of users lower; Wilcoxon p = {ls['hrv_wilcoxon_p']:.2g}).",
                  f"- **Interpretation:** {ls['interpretation']}", "", "![LifeSnaps boxplot](lifesnaps_boxplot.png)", ""]
        else:
            L += [ls.get("note", "not available"), ""]

    L += ["## 5. Honest limitations", "",
          "- Trained and tested on **simulated** patients; the glucose labels come from the same simulator that "
          "encodes the sleep -> insulin-sensitivity effect, so the next-day results show the pipeline works, not "
          "clinical validity (circularity).",
          "- Pooled AUROC is helped by easy between-patient differences (healthy people almost never spike); the "
          "T2D-only subgroup number is the harder test.",
          "- NHANES is a US population; Indian-specific calibration (e.g. ICMR-INDIAB) is future work.",
          "- Genetic markers are simulated from published allele frequencies with small effects.",
          "- Next step: retrospective validation on real, anonymized CGM + wearable data with ethics approval.", ""]
    text = "\n".join(L)
    (REPORTS / "results.md").write_text(text, encoding="utf-8")
    return text


if __name__ == "__main__":
    print(write_results())
